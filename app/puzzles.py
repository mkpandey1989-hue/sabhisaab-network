def _hash(stem: str) -> str:
    return hashlib.sha256(stem.strip().lower().encode("utf-8")).hexdigest()[:16]


import re as _re
_EMOJI = _re.compile("[\U0001F000-\U0001FAFF\u2600-\u27BF\u2B00-\u2BFF\uFE0F\u200D\u23E9-\u23FA]")


def _strip_code(stem: str) -> str:
    """Hash ke liye: reel-code hata kar asli sawal (pehle code ki wajah se har sawal alag lagta tha)."""
    return _re.sub(r"\s*\(?(?:Code\s*)?#\d{3,6}\)?", "", stem or "").strip()


def _no_emoji(t):
    return _re.sub(r"\s{2,}", " ", _EMOJI.sub("", t or "")).strip()


