def _exam_time_work(category: str = "Banking", rnd=None) -> dict:
    """WA0002 Sec 3: Generates a dual-verified Banking/SSC/Railway exam question with full JSON schema:
    question_id, exam_category, subject, topic, difficulty_level, question_stem, options, correct_answer,
    step_by_step_explanation, shortcut_trick, verification_hash, most_picked_wrong_option."""
    rnd = rnd or random.Random()
    a_days = rnd.choice([10, 12, 15, 20])
    b_days = rnd.choice([15, 20, 30, 60])
    while (a_days * b_days) % (a_days + b_days) != 0:
        a_days = rnd.choice([10, 12, 15, 20])
        b_days = rnd.choice([15, 20, 30, 60])
    # Method 1: Algebraic formula (A*B)/(A+B)
    ans1 = (a_days * b_days) // (a_days + b_days)
    # Method 2: LCM work units simulation
    import math as _m
    lcm_w = (a_days * b_days) // _m.gcd(a_days, b_days)
    ans2 = lcm_w // ((lcm_w // a_days) + (lcm_w // b_days))
    assert ans1 == ans2, "Time & Work dual-solver mismatch"
    stem = f"यदि A किसी काम को {a_days} दिन में और B उसी काम को {b_days} दिन में पूरा करता है, तो दोनों मिलकर उसे कितने दिन में पूरा करेंगे?"
    wrong_common = f"{(a_days + b_days) // 2} दिन"
    opts = [f"{ans1} दिन", wrong_common, f"{ans1 + 2} दिन", f"{max(1, ans1 - 1)} दिन"]
    q_hash = _hash(stem)
    return {
        "question_id": f"EX-{q_hash[:8].upper()}",
        "exam_category": category,
        "subject": "Quant",
        "topic": "Time and Work (समय और कार्य)",
        "difficulty_level": "Medium",
        "question_stem": stem,
        "options": opts,
        "correct_answer": f"{ans1} दिन",
        "most_picked_wrong_option": f"आम गलती: {wrong_common} (दोनों का औसत निकाल लेना)",
        "step_by_step_explanation": (
            f"कुल कार्य = {a_days} और {b_days} का LCM = {lcm_w} यूनिट। "
            f"A की क्षमता = {lcm_w // a_days} यूनिट/दिन, B की क्षमता = {lcm_w // b_days} यूनिट/दिन। "
            f"दोनों का समय = {lcm_w} ÷ {(lcm_w // a_days) + (lcm_w // b_days)} = {ans1} दिन।"
        ),
        "shortcut_trick": f"सीधा फॉर्मूला: (A × B) ÷ (A + B) = ({a_days} × {b_days}) ÷ {a_days + b_days} = {ans1} दिन!",
        "verification_hash": q_hash,
    }
