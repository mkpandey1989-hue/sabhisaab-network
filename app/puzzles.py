def dual_verify_math(expr_type: str, a: int, b: int, c: int = 0) -> tuple:
    """Dual-method verification: Method 1 (Direct algebraic formula) vs Method 2 (Iterative/Simulation)."""
    if expr_type == "bodmas":
        ans1 = a + (b * c)
        ans2 = a + sum(b for _ in range(c))
    elif expr_type == "square_diff":
        ans1 = (a * a) - (b * b)
        ans2 = (a - b) * (a + b)
    elif expr_type == "percent":
        ans1 = a * b
        ans2 = int(round((a / 100.0) * (b * 100)))
    elif expr_type == "triangles_in_grid":
        # n vertical segments inside a triangle -> n*(n+1)//2 triangles
        ans1 = a * (a + 1) // 2
        ans2 = sum(range(1, a + 1))
    else:
        ans1 = ans2 = a + b
    assert ans1 == ans2, f"Dual verification mismatch: {ans1} != {ans2}"
    return True, ans1


def _unique_reel_code(rnd):
    """v2.5.2: 4 ank ka code (1000-9999), jo reel_codes ya /jawab answer_key mein pehle se na ho. Bharne par 5 ank.
    Purane 3 ank wale code jaise the waise (lookup_code mein). Pehle 101-998 mein overwrite hota tha (B-04)."""
    used = set((state.get("reel_codes") or {}).keys())
    used |= {str(x.get("code")) for x in (state.get("answer_key") or [])}
    for lo, hi in ((1000, 9999), (10000, 99999)):
        for _ in range(300):
            c = str(rnd.randint(lo, hi))
            if c not in used:
                return c
    return str(rnd.randint(100000, 999999))


