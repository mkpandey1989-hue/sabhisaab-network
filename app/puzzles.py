def _distractors(kind, ans, rnd):
    """Sach jaise 3 galat vikalp (pehle 'विकल्प B / C' likha aata tha)."""
    out = []
    if kind == "color_match":
        out = [f"बॉक्स नंबर {n}" for n in (1, 2, 3, 4) if f"बॉक्स नंबर {n}" != ans]
    elif kind == "ball_memory":
        out = [f"कटोरी {c}" for c in "ABC" if f"कटोरी {c}" != ans]
    elif kind == "odd_one_out":
        m = _re.search(r"स्थान (\d+) पर '(.+?)'", ans)
        if m:
            out = [f"स्थान {n} पर '{m.group(2)}'" for n in (1, 2, 3, 4, 5) if str(n) != m.group(1)]
    elif kind == "matchstick":
        m = _re.match(r"\s*(\d+)\s*([+\-])\s*(\d+)\s*=\s*(\d+)", ans)
        if m:
            a, op, b, c = int(m.group(1)), m.group(2), int(m.group(3)), int(m.group(4))
            for a2, op2, b2 in ((a - 1, op, b), (a, op, b + 1), (a + 1, op, b), (a, "+" if op == "-" else "-", b)):
                val = a2 + b2 if op2 == "+" else a2 - b2
                if val != c and a2 >= 0:
                    out.append(f"{a2} {op2} {b2} = {c}")
    elif kind == "memory_flash":
        out = [w for w in ("घड़ी", "चाबी", "चश्मा", "कलम", "मोबाइल", "छाता", "बटुआ") if w not in ans]
    elif kind == "word_scramble":
        out = [w for w in ("बचत", "कमाई", "ब्याज", "किस्त", "बजट", "खर्च", "मुनाफ़ा", "उधार") if w != ans]
    if len(out) < 3:
        m = _re.search(r"\d+", ans)
        if m:
            n = int(m.group())
            cands = [n + 1, n - 1, n + 2, n * 2, max(1, n // 2), n + 5, n - 5, n + 10]
            out += [ans[:m.start()] + str(c) + ans[m.end():] for c in dict.fromkeys(cands) if c > 0 and c != n]
    out = [x for x in dict.fromkeys(out) if x != ans]
    rnd.shuffle(out)
    return (out + ["इनमें से कोई नहीं"])[:3]


