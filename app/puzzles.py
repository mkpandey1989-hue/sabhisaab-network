def _opts4(ans, rnd, spread=(1, 2, 3, 4, 5, 6)):
    out = [ans]
    tries = 0
    while len(out) < 4 and tries < 60:
        tries += 1
        d = rnd.choice(spread) * rnd.choice((-1, 1))
        v = ans + d
        if v > 0 and v not in out:
            out.append(v)
    rnd.shuffle(out)
    return [str(x) for x in out]


